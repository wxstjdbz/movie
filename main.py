# 월 × 요일별 일관객 합계 히트맵
# ============================================================

st.divider()

st.header("그래프 5. 월 × 요일별 일관객 합계")

st.write(
    "날짜에서 월과 요일을 뽑아 월별·요일별 일관객 합계를 비교합니다."
)


# ------------------------------------------------------------
# 월과 요일 추출
# ------------------------------------------------------------

heatmap_df = df.copy()

# 월 추출
heatmap_df["월"] = heatmap_df["날짜"].dt.month

# 요일 추출
weekday_names = [
    "월요일",
    "화요일",
    "수요일",
    "목요일",
    "금요일",
    "토요일",
    "일요일"
]

heatmap_df["요일"] = heatmap_df["날짜"].dt.dayofweek.map(
    lambda x: weekday_names[x]
)


# ------------------------------------------------------------
# 월 × 요일별 일관객 합계 계산
# ------------------------------------------------------------

heatmap_data = (
    heatmap_df
    .groupby(
        ["월", "요일"],
        as_index=False
    )["일관객"]
    .sum()
)


# ------------------------------------------------------------
# 히트맵용 표 만들기
# ------------------------------------------------------------

heatmap_table = heatmap_data.pivot(
    index="월",
    columns="요일",
    values="일관객"
)


# 요일 순서 고정
heatmap_table = heatmap_table.reindex(
    columns=weekday_names
)


# 월 순서 고정
heatmap_table = heatmap_table.reindex(
    index=range(1, 13)
)


# ------------------------------------------------------------
# 히트맵 그래프
# ------------------------------------------------------------

fig5 = px.imshow(
    heatmap_table,
    labels={
        "x": "요일",
        "y": "월",
        "color": "일관객 합계"
    },
    x=weekday_names,
    y=[f"{month}월" for month in range(1, 13)],
    text_auto=".2s",
    aspect="auto",
    title="월 × 요일별 박스오피스 10위권 일관객 합계"
)


# ------------------------------------------------------------
# 마우스를 올렸을 때 표시
# ------------------------------------------------------------

fig5.update_traces(
    hovertemplate=(
        "%{y} %{x}"
        "<br>"
        "일관객 합계: %{z:,.0f}명"
        "<extra></extra>"
    )
)


# ------------------------------------------------------------
# 그래프 설정
# ------------------------------------------------------------

fig5.update_layout(
    xaxis_title="요일",
    yaxis_title="월",
    coloraxis_colorbar_title="일관객"
)


# 그래프 출력
st.plotly_chart(
    fig5,
    use_container_width=True
)


